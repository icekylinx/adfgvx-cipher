def omit_top_navigation(body):
    """Remove generic leading navigation, retaining source and evidence links."""
    result = []
    at_top = True
    for line in body.splitlines(keepends=True):
        stripped = line.strip()
        if at_top and (not stripped or re.fullmatch(r'<a\s+(?:id|name)=["\'][^"\']+["\']></a>', stripped)):
            result.append(line)
            continue
        if at_top:
            links = list(re.finditer(r'\[([^\]]+)\]\([^\s)]+\)', stripped))
            remainder = re.sub(r'\[[^\]]+\]\([^\s)]+\)', '', stripped)
            if links and not remainder.strip(' ·|'):
                kept = [match[0] for match in links if match[1] not in NAVIGATION_LABELS]
                if len(kept) != len(links):
                    if kept:
                        result.append(' · '.join(kept) + '\n')
                    continue
        at_top = False
        result.append(line)
    return ''.join(result)


def source_anchor(source_id):
    return 'source-' + source_id.lower().replace('_', '-')


def case_anchor(case_path):
    return 'edition-' + re.sub(r'[^a-z0-9-]', '-', case_path[:-3].lower()).strip('-')


def heading_slug(label):
    return re.sub(r'[^\w\- ]', '', plain_heading(label).lower()).replace(' ', '-')


def rebase_target(target, source, destination, included, catalogue=None, root=ROOT):
    """Move a Markdown destination and redirect embedded-case links locally."""
    bracketed = target.startswith('<') and target.endswith('>')
    value = target[1:-1] if bracketed else target
    parsed = urlsplit(value)
    if parsed.scheme or parsed.netloc or value.startswith('//'):
        return target
    path = unquote(parsed.path)
    resolved = (posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
                if path else source)
    assert not resolved.startswith('../') and not resolved.startswith('/'), (source, target)
    fragment = unquote(parsed.fragment)
    if resolved in included and not parsed.query:
        prefix = included[resolved]
        result = '#' + prefix + ('-' + fragment if fragment else '')
    else:
        mapped = urlsplit(page_target(resolved + ('#' + fragment if fragment else ''),
                                      catalogue=catalogue, root=root))
        resolved, fragment = mapped.path, mapped.fragment
        relocated = posixpath.relpath(resolved, posixpath.dirname(destination))
        result = urlunsplit(('', '', relocated, parsed.query, fragment))
    return '<' + result + '>' if bracketed else result


def embed_case(text, source, destination, included, catalogue=None, root=ROOT):
    """Rebase one entire case body, preserving fenced streams and inner drawers."""
    prefix = included[source]
    title_match = re.search(r'^# [^\n]*(?:\n|$)', text, re.M)
    assert title_match is not None, source
    title_line = title_match[0].rstrip('\n')
    body = omit_top_navigation(text[:title_match.start()] + text[title_match.end():])
    title = plain_heading(title_line[2:])
    occurrences = defaultdict(int)
    occurrences[heading_slug(title_line[2:])] = 1
    emitted = set()
    lines = [f'<a id="{prefix}-{heading_slug(title_line[2:])}"></a>\n\n']
    emitted.add(prefix + '-' + heading_slug(title_line[2:]))
    fence = None
    for line in body.splitlines(keepends=True):
        marker = FENCE.match(line)
        if marker:
            token = marker.group(1)
            if fence is None:
                fence = token
            elif token[0] == fence[0] and len(token) >= len(fence):
                fence = None
            lines.append(line)
            continue
        if fence is not None:
            lines.append(line)
            continue

        def explicit(match):
            name = prefix + '-' + html.unescape(match[2])
            # A legacy explicit alias may repeat a heading slug. One anchor is enough.
            if name in emitted:
                return match[1] + name + match[3]
            emitted.add(name)
            return match[1] + html.escape(name, quote=True) + match[3]

        line = EXPLICIT_ANCHOR.sub(explicit, line)
        heading = HEADING.match(line.rstrip('\n'))
        if heading:
            old_slug = heading_slug(heading[3])
            occurrence = occurrences[old_slug]
            occurrences[old_slug] += 1
            if occurrence:
                old_slug += '-' + str(occurrence)
            name = prefix + '-' + old_slug
            if name not in emitted:
                lines.extend([f'<a id="{name}"></a>\n', '\n'])
                emitted.add(name)
            level = min(6, len(heading[2]) + 1)
            if (source == 'cases/finance/crown_cash_requests.md'
                    and heading[3] == 'The 11th-Army addresses'):
                level = 3
            display = REVIEWED_DISPLAY_HEADINGS.get(source, {}).get(heading[3], heading[3])
            line = '#' * level + ' ' + display + '\n'

        def relocate(target):
            return rebase_target(target, source, destination, included, catalogue, root)

        line = LINK_DESTINATION.sub(lambda m: m[1] + relocate(m[2]), line)
        line = REFERENCE.sub(lambda m: m[1] + relocate(m[2]), line)
        line = HTML_DESTINATION.sub(lambda m: m[1] + relocate(m[2]) + m[3], line)
        lines.append(line)
    assert fence is None, (source, 'Unclosed source fence')
    return title, ''.join(lines).strip() + '\n'


def focus_page_sections(body, page, case, all_rows, locations):
    """Move explicitly scoped sections forward without cutting shared arguments.

    Only original H2 sections outside fences and drawers are separable. A
    catalogue fragment must identify that section's own heading, not an anchor
    nested inside it. Unclassified sections remain visible; complete sections
    explicitly belonging only to other pages become comparative evidence.
    """
    lines = body.splitlines(keepends=True)
    sections = []
    fence = None
    depth = 0
    for index, line in enumerate(lines):
        marker = FENCE.match(line)
        if marker:
            token = marker[1]
            if fence is None:
                fence = token
            elif token[0] == fence[0] and len(token) >= len(fence):
                fence = None
            continue
        if fence is not None:
            continue
        heading = HEADING.match(line.rstrip('\n'))
        if heading and len(heading[2]) == 3 and depth == 0:
            start = index
            while start and (not lines[start - 1].strip()
                             or re.fullmatch(r'<a\s+(?:id|name)=["\'][^"\']+["\']></a>\s*',
                                             lines[start - 1])):
                start -= 1
            heading_anchors = set(re.findall(r'<a\s+(?:id|name)=["\']([^"\']+)',
                                            ''.join(lines[start:index])))
            sections.append((start, plain_heading(heading[3]), heading_anchors))
        depth += len(re.findall(r'<details(?:\s[^>]*)?>', line))
        depth -= line.count('</details>')
        if depth < 0:
            return body
    if fence is not None or depth or not sections:
        return body

    scoped = [r for r in all_rows if r['path'].split('#')[0] == case]
    prefix = case_anchor(case)
    current, shared, other = [], [], []
    for i, (start, title, heading_anchors) in enumerate(sections):
        end = sections[i + 1][0] if i + 1 < len(sections) else len(lines)
        block = ''.join(lines[start:end])
        pages = set()
        for fragment, source_ids in REVIEWED_SECTION_SOURCES.get(case, {}).items():
            if prefix + '-' + fragment in heading_anchors:
                pages.update(locations[ident][0] if ident in locations
                             else NON_CIPHER_SOURCE_PAGES[ident] for ident in source_ids)
        source_heading = any(re.match(re.escape(r['label']) + r'(?![A-Za-z0-9])', title)
                             for r in scoped)
        for row in scoped:
            _, _, fragment = row['path'].partition('#')
            # Source-labelled headings are metadata, not incidental page numbers.
            label = row['label']
            named = source_heading and re.search(re.escape(label) + r'(?![A-Za-z0-9])', title)
            if named or (fragment and prefix + '-' + fragment in heading_anchors):
                pages.add(locations[row['id']][0])
        if page in pages:
            current.append(block)
        elif pages:
            other.append(block)
        else:
            shared.append(block)
    result = ''.join(lines[:sections[0][0]]) + ''.join(current + shared)
    if other:
        result += ('\n\n<details>\n<summary>Comparative source sections from other printed pages</summary>\n\n'
                   + ''.join(other).strip('\n') + '\n\n</details>\n')
    return result


def attach_source_anchors(body, group, prefix):
    """Place stable source URLs at their reading, rather than in the contents table."""
    leading = []
    by_target = defaultdict(list)
    for row in group:
        _, _, fragment = row['path'].partition('#')
        anchor = f'<a id="{source_anchor(row["id"])}"></a>\n'
        if fragment:
            by_target[prefix + '-' + fragment].append(anchor)
        else:
            leading.append(anchor)
    for target, additions in by_target.items():
        marker = f'<a id="{target}"></a>'
        assert body.count(marker) == 1, (target, 'Source target is not unique')
        body = body.replace(marker, ''.join(additions) + marker, 1)
    return ''.join(leading), body


def rows_by_page(catalogue, locations):
    pages = defaultdict(list)
    for group in ('challenge', 'other'):
        for row in catalogue[group]:
            pages[locations[row['id']][0]].append(row)
    for rows in pages.values():
        rows.sort(key=lambda r: (natural_key(locations[r['id']][1]), natural_key(r['id'])))
    return dict(sorted(pages.items()))


def render_page(page, rows, all_rows, locations, originals, previous=None, following=None,
                catalogue=None, root=ROOT):
    destination = f'pages/{page:03d}.md'
    groups = {}
    for row in rows:
        groups.setdefault(row['path'].split('#')[0], []).append(row)
    included = {path: case_anchor(path) for path in groups}
    links = ['[Page ranges](README.md)', '[By subject](../topics/README.md)',
             '[Historical research](../docs/historical-studies/README.md)',
             '[Reading conventions](../docs/reading-conventions.md)']
    if previous is not None:
        links.append(f'[← p{previous}]({previous:03d}.md)')
    if following is not None:
        links.append(f'[p{following} →]({following:03d}.md)')
    old_title = heading_slug(f'Childs p. {page} — readings and source edition')
    lines = [f'# Childs p{page} — readings and source edition', '',
             f'<a id="{old_title}"></a>', '', GENERATED, '',
             ' · '.join(links), '',
             f"German readings, English interpretations and source explanations for the **{len(rows)} "
             + ('ciphertext' if len(rows) == 1 else 'ciphertexts') + '** on this printed page.', '',
             '| Source | State | Subject |', '|---|---|---|']
    for row in rows:
        label = row['label'].replace('|', '\\|')
        subject = row['subject'].replace('|', '\\|')
        lines.append(f'| [{label}](#{source_anchor(row["id"])}) | {row["state"]} | {subject} |')
    lines.append('')
    for case, group in groups.items():
        title, body = embed_case(originals[case], case, destination, included, catalogue, root)
        body = focus_page_sections(body, page, case, all_rows, locations)
        leading, body = attach_source_anchors(body, group, included[case])
        labels = ', '.join(r['label'] for r in group)
        heading = group[0]['subject'] if len(group) == 1 else title
        lines.extend([leading.rstrip(), f'<a id="{included[case]}"></a>', ''])
        if len(group) > 1:
            old_heading = heading_slug(f'{labels} — {heading}')
            lines.extend([f'<a id="{old_heading}"></a>', '', f'## {heading}', '',
                          f'**Sources on this page:** {labels}.', ''])
        else:
            lines.extend([f'## {labels} — {heading}', ''])
        if heading != title:
            lines.extend([f'**Edition context:** {title}.', ''])
        companions = [r for r in all_rows if r['path'].split('#')[0] == case
                      and locations[r['id']][0] != page]
        if companions:
            companions.sort(key=lambda r: (locations[r['id']][0], natural_key(locations[r['id']][1])))
            companion_links = ', '.join(f'[{r["label"]}]({locations[r["id"]][0]:03d}.md#{source_anchor(r["id"])})'
                                        for r in companions)
            lines.extend(['**Related source pages:** '
                          + companion_links + '.', ''])
        lines.extend([body.rstrip(), ''])
    return style_markdown('\n'.join(lines))


def generate(catalogue, root=ROOT, locations=None):
    locations = source_locations(catalogue) if locations is None else locations
    pages = rows_by_page(catalogue, locations)
    all_rows = catalogue['challenge'] + catalogue['other']
    originals = load_editions(root)
    required = {r['path'].split('#')[0] for r in all_rows}
    assert required <= originals.keys(), 'Missing source editions: ' + str(sorted(required - originals.keys()))
    numbers = list(pages)
    result = {}
    for index, page in enumerate(numbers):
        previous = numbers[index - 1] if index else None
        following = numbers[index + 1] if index + 1 < len(numbers) else None
        result[root / f'pages/{page:03d}.md'] = render_page(
            page, pages[page], all_rows, locations, originals, previous, following, catalogue, root)
    return result


def validate(generated, catalogue, root=ROOT, locations=None):
    """Check exact source coverage and every generated local link, including images."""
    root = root.resolve()
    locations = source_locations(catalogue) if locations is None else locations
    expected = {row['id']: row for key in ('challenge', 'other') for row in catalogue[key]}
    expected_anchors = {source_anchor(ident): ident for ident in expected}
    assert len(expected_anchors) == len(expected)
    counts = Counter()
    cache = {}
    checked = 0
    for path, text in generated.items():
        prose = ''.join(prose_lines(text))
        assert len(re.findall(r'^# ', prose, re.M)) == 1, (path, 'Require one page title')
        assert prose.count('<details>') == prose.count('</details>'), (path, 'Unbalanced evidence drawers')
        assert prose.count('<details>') == len(re.findall(r'<summary>[^<]+</summary>', prose)), (path, 'Evidence drawer summaries differ')
        ids = re.findall(r'<a\s+(?:id|name)=["\']([^"\']+)', text)
        assert len(ids) == len(set(ids)), (path, 'Duplicate explicit anchors')
        for anchor in ids:
            if anchor in expected_anchors:
                ident = expected_anchors[anchor]
                assert int(path.stem) == locations[ident][0], (ident, 'Wrong printed page')
                counts[ident] += 1
        assert re.match(r'^# Childs p\d+ — ', text) and GENERATED in text
        for target in targets(text):
            parsed = urlsplit(target)
            if parsed.scheme or parsed.netloc or target.startswith('//'):
                continue
            destination = (path.parent / unquote(parsed.path)).resolve() if parsed.path else path
            assert destination.is_relative_to(root), (path, target, 'Outside repository')
            assert destination.exists() or destination in generated, (path, target, 'Missing file')
            if destination.is_dir() and (destination / 'README.md').is_file():
                destination /= 'README.md'
            if parsed.fragment and destination.suffix.lower() == '.md':
                if destination not in cache:
                    cache[destination] = anchors(generated.get(destination, '') or destination.read_text())
                assert unquote(parsed.fragment) in cache[destination], (path, target, 'Missing anchor')
            checked += 1
    assert counts == Counter({ident: 1 for ident in expected}), 'Each source must occur on exactly one printed page'
    assert {int(path.stem) for path in generated} == {place[0] for place in locations.values()}
    return {'pages': len(generated), 'sources': sum(counts.values()), 'local_links': checked}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify generated page editions without writing')
    args = parser.parse_args()
    catalogue = load_catalog()
    generated = generate(catalogue)
    summary = validate(generated, catalogue)
    current = {path for path in (ROOT / 'pages').glob('[0-9][0-9][0-9].md')
               if GENERATED in path.read_text()}
    assert not current - generated.keys(), 'Obsolete generated page editions remain'
    if args.check:
        mismatches = [str(path.relative_to(ROOT)) for path, text in generated.items()
                      if not path.is_file() or path.read_text() != text]
        assert not mismatches, 'Regenerate full page editions: ' + ', '.join(mismatches)
    else:
        for path, text in generated.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print('Full printed-page editions: ' + ', '.join(f'{key}={value}' for key, value in summary.items()) + '; verified.')


if __name__ == '__main__':
    main()
