TOPIC_ROOT = ROOT / 'topics'
GENERATED = '<!-- Generated by python -m adfgvx.navigation; edit data/topic_exploration.json and data/reading_groups.json. -->'
LINK = re.compile(r'\]\((<[^>]+>|[^\s)]+)(?:\s+["\'][^"\']*["\'])?\)')
REFERENCE = re.compile(r'^\s{0,3}\[(?!\^)[^\]]+\]:\s*(<[^>]+>|\S+)')


def prose_lines(text):
    """Exclude fenced examples from link and heading checks."""
    fence = None
    for line in text.splitlines(keepends=True):
        marker = re.match(r'^\s{0,3}(`{3,}|~{3,})', line)
        if marker:
            token = marker.group(1)
            if fence is None:
                fence = token
            elif token[0] == fence[0] and len(token) >= len(fence):
                fence = None
            continue
        if fence is None:
            yield line


def plain_heading(text):
    text = re.sub(r'!?\[([^\]]*)\]\([^)]*\)', r'\1', text)
    text = re.sub(r'<[^>]*>', '', text)
    return html.unescape(text.replace('`', '').replace('*', '').strip())


def anchors(text):
    """GitHub-style heading slugs plus explicit HTML anchors."""
    result, occurrences = {}, defaultdict(int)
    for line in prose_lines(text):
        for match in re.finditer(r'<a\s+(?:id|name)=["\']([^"\']+)["\']', line, re.I):
            result[html.unescape(match.group(1))] = html.unescape(match.group(1))
        heading = re.match(r'^\s{0,3}#{1,6}\s+(.+?)(?:\s+#+)?\s*$', line)
        if not heading:
            continue
        label = plain_heading(heading.group(1))
        slug = re.sub(r'[^\w\- ]', '', label.lower()).replace(' ', '-')
        occurrence = occurrences[slug]
        occurrences[slug] += 1
        if occurrence:
            slug += '-' + str(occurrence)
        result.setdefault(slug, label)
    return result


def targets(text):
    for line in prose_lines(text):
        for match in LINK.finditer(line):
            yield match.group(1).strip('<>')
        definition = REFERENCE.match(line)
        if definition:
            yield definition.group(1).strip('<>')


def page_title(path):
    for line in prose_lines(path.read_text()):
        if line.startswith('# '):
            return plain_heading(line[2:])
    raise AssertionError(f'Missing case title: {path.relative_to(ROOT)}')


def load_groups(catalogue):
    """Classify logical source records without recreating deleted case pages."""
    settings = json.loads((ROOT / 'data/reading_groups.json').read_text())
    groups = settings['groups']
    assert {g['id'] for g in groups} == {
        'caucasus', 'naval', 'military', 'radio', 'finance', 'people', 'open'}
    assert len({g['id'] for g in groups}) == len(groups)
    rows = {g['id']: [] for g in groups}
    challenge_ids = {r['id'] for r in catalogue['challenge']}
    for group in groups:
        assert group['directory'] == 'cases/' + group['id']
        assert set(group.get('related_challenge_ids', [])) <= challenge_ids
        for path in group.get('additional_case_paths', []):
            assert source_exists(ROOT / path), path
    for row in catalogue['other']:
        path = row['path'].split('#')[0]
        matches = [g['id'] for g in groups
                   if path.startswith(g['directory'] + '/')
                   or path in g.get('additional_case_paths', [])]
        assert len(matches) == 1, f"Assign exactly one reading topic: {row['id']} ({path})"
        rows[matches[0]].append(row)
    for row in catalogue['challenge']:
        matches = [g['id'] for g in groups
                   if row['id'] in g.get('related_challenge_ids', [])]
        assert matches, f"Challenge lacks a reading topic: {row['id']}"
        for ident in matches:
            rows[ident].append(row)
    locations = physical_source_accounting(catalogue)['locations']
    for ident, value in rows.items():
        value.sort(key=lambda r: (locations[r['id']][0],
                                 natural_key(locations[r['id']][1]), r['id']))
        assert all((r['state'] == 'OPEN') == (ident == 'open') for r in value)
    expected = {r['id'] for key in ('challenge', 'other') for r in catalogue[key]}
    assert {r['id'] for value in rows.values() for r in value} == expected
    assert len(rows['open']) == 7
    return groups, rows


def load_exploration(catalogue):
    data = json.loads((ROOT / 'data/topic_exploration.json').read_text())
    assert data['schema'] == 'adfgvx-topic-exploration-v1'
    assert set(data['topics']) == {'caucasus', 'naval', 'military', 'radio', 'finance', 'people'}
    sources = {r['id']: r for key in ('challenge', 'other') for r in catalogue[key]}
    for topic in data['topics'].values():
        assert (ROOT / 'docs/historical-studies' / topic['study']).is_file(), topic['study']
        for study in topic.get('related_studies', []):
            assert (ROOT / 'docs/historical-studies' / study['study']).is_file(), study['study']
        for section in topic['sections']:
            assert section['title'] and section['text'] and section['entries']
            for entry in section['entries']:
                assert entry['title'] and entry['summary'] and entry['source_ids']
                assert len(set(entry['source_ids'])) == len(entry['source_ids'])
                for ident in entry['source_ids']:
                    assert ident in sources, ident
                    assert sources[ident]['state'] != 'OPEN', ident
    assert data['secondary']['catalogue_state'] == 'OPEN'
    return data, sources


def cell(text):
    return text.replace('|', '\\|').replace('\n', ' ')


def curated_table(entries, sources, destination):
    lines = ['| Subject | Summary | Page editions |', '|---|---|---|']
    for entry in entries:
        links, seen = [], set()
        for ident in entry['source_ids']:
            target = source_target(sources[ident])
            page = int(Path(target.split('#', 1)[0]).stem)
            if page in seen:
                continue
            seen.add(page)
            link = relative_link(target, destination)
            links.append(f"[p{page}]({link})")
        lines.append(f"| **{cell(entry['title'])}** | {cell(entry['summary'])} | {' · '.join(links)} |")
    return '\n'.join(lines)


def render_topic(group, rows, catalogue):
    destination = TOPIC_ROOT / (group['id'] + '.md')
    data, sources = load_exploration(catalogue)
    lines = ['# ' + group['title'], '', GENERATED, '',
             '[By subject](README.md) · [Page ranges](../pages/README.md) · '
             '[Historical research](../docs/historical-studies/README.md)', '']
    if group['id'] == 'open':
        lines.extend([data['secondary']['text'], '',
                      '## Seven unresolved sources', '', table(rows, destination), '',
                      '[Current research](../docs/research-status.md#unresolved-sources) · '
                      '[Source inventory](../docs/whole-material-coverage.md)', ''])
        return '\n'.join(lines)
    editorial = data['topics'][group['id']]
    lines.extend([f"**Historical study:** [{editorial['study_title']}](../docs/historical-studies/{editorial['study']}).", ''])
    for study in editorial.get('related_studies', []):
        lines.extend([f"**Related study:** [{study['study_title']}](../docs/historical-studies/{study['study']}).", ''])
    for section in editorial['sections']:
        lines.extend(['## ' + section['title'], '', section['text'], '',
                      curated_table(section['entries'], sources, destination), ''])
    lines.extend(['## Complete source index', '',
                  f'{len(rows)} physical sources, including related original challenges. '
                  '[Reading states](../docs/reading-conventions.md#catalogue-states).', '',
                  '<details>', '<summary>Browse every source in printed-page order</summary>', '',
                  table(rows, destination), '', '</details>', ''])
    return '\n'.join(lines)


def render_overview(groups, rows, catalogue=None):
    catalogue = load_catalog() if catalogue is None else catalogue
    destination = TOPIC_ROOT / 'README.md'
    accounting = physical_source_accounting(catalogue)
    data, _ = load_exploration(catalogue)
    lines = ['# Browse by subject', '', GENERATED, '',
             '[ADFGVX Cipher](../README.md) · [Page ranges](../pages/README.md) · '
             '[Historical research](../docs/historical-studies/README.md)', '',
             'Choose a subject for short summaries and direct links to the complete page editions. Each guide also includes its full source index.', '',
             '## Subjects', '',
             '| Subject | Material | Historical study |', '|---|---|---|']
    for group in groups:
        if group['id'] == 'open':
            continue
        editorial = data['topics'][group['id']]
        lines.append(f"| [{group['title']}]({group['id']}.md) | {cell(group['summary'])} | [{editorial['study_title']}](../docs/historical-studies/{editorial['study']}) |")
    lines.extend(['', '[Seven unresolved sources](open.md) remain available with their source texts.', '',
                  '## Original challenges', '',
                  '<details>', '<summary>The 22 Lasry–Schmeh challenge sources</summary>', '',
                  table(catalogue['challenge'], destination), '', '</details>', ''])
    return '\n'.join(lines)


def check_links(paths):
    known_anchors, checked, failures = {}, 0, []
    for source in sorted(paths):
        for target in targets(source.read_text()):
            if urlsplit(target).scheme or target.startswith('//'):
                continue
            file, _, fragment = target.partition('#')
            file = unquote(file.partition('?')[0])
            destination = (source.parent / file).resolve() if file else source
            try:
                destination.relative_to(ROOT)
            except ValueError:
                failures.append(f'{source.relative_to(ROOT)} -> {target}: outside repository')
                continue
            if not destination.exists():
                failures.append(f'{source.relative_to(ROOT)} -> {target}: missing file')
                continue
            checked += 1
            if destination.is_dir() and (destination / 'README.md').is_file():
                destination /= 'README.md'
            if fragment and destination.suffix.lower() == '.md':
                if destination not in known_anchors:
                    known_anchors[destination] = anchors(destination.read_text())
                if unquote(fragment) not in known_anchors[destination]:
                    failures.append(f'{source.relative_to(ROOT)} -> {target}: missing section')
    assert not failures, '\n'.join(failures)
    return checked


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify generated subject guides and local links without writing')
    args = parser.parse_args()
    catalogue = load_catalog()
    groups, rows = load_groups(catalogue)
    generated = {TOPIC_ROOT / (g['id'] + '.md'): render_topic(g, rows[g['id']], catalogue)
                 for g in groups}
    generated[TOPIC_ROOT / 'README.md'] = render_overview(groups, rows, catalogue)
    generated = {path: style_markdown(text) for path, text in generated.items()}
    for path, expected in generated.items():
        if args.check:
            assert path.is_file() and path.read_text() == expected, f'Regenerate navigation: {path.relative_to(ROOT)}'
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    paths = set(generated) | {ROOT / 'README.md', ROOT / 'CONTRIBUTING.md',
                              ROOT / 'experiments/README.md', ROOT / 'sources/README.md',
                              ROOT / 'data/README.md'}
    paths |= set((ROOT / 'docs').rglob('*.md'))
    checked = check_links(paths)
    accounting = physical_source_accounting(catalogue)
    print(f"Navigation: six subjects and OPEN, {accounting['unique_physical_sources']} physical sources, "
          f'{len(generated)} topic guides; {checked} local links and Markdown sections checked.')


if __name__ == '__main__':
    main()
