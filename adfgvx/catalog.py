"""Build compact reading guides and page-number indexes from one catalogue.

ADFGVX Cipher — icekylinx and GPT-6 Astra Pro.
Each physical source has one canonical entry, including sources still OPEN.
Uninspected OCR candidates are not admitted.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import hashlib
import json
import posixpath
from pathlib import Path
import re

from .source_editions import source_exists

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/reading_catalog.json"
SOURCE_ALIASES = ROOT / "data/source_record_aliases.json"
SOURCE_CENSUS = ROOT / "data/reviews/childs_material_census_20261103.json"
STATES = ("READING", "PARTIAL", "CONDITIONAL", "OPEN")
START = "<!-- READING-CATALOG:START -->"
END = "<!-- READING-CATALOG:END -->"
PAGE_ROOT = ROOT / "cases/pages"
PAGE_BAND_SIZE = 25
GENERATED = "<!-- Generated by python -m adfgvx.catalog; edit data/reading_catalog.json. -->"


def source_messages():
    return {m["id"]: m for m in json.loads((ROOT / "data/messages.json").read_text())["messages"]}


def source_locations(catalogue):
    """Return exact physical locations without equating similar message bodies."""
    messages = source_messages()
    locations = {}
    for group in ("challenge", "other"):
        for row in catalogue[group]:
            if group == "challenge":
                source = messages[row["id"]]["source"]
                page, section = source["printed_page"], source["section"]
            else:
                page, section = row["printed_page"], row["source_section"]
            assert isinstance(page, int) and page > 0, row["id"]
            assert isinstance(section, str) and section and section == section.strip(), row["id"]
            assert row["id"] not in locations, row["id"]
            locations[row["id"]] = (page, section)
    return locations


def source_record_aliases():
    """Verify identifiers retained inside older evidence, never catalogue rows.

    An alias requires identical complete source bytes and the same physical
    location. Similar plaintext and separately received copies are insufficient.
    """
    data = json.loads(SOURCE_ALIASES.read_text())
    assert data["schema"] == "adfgvx-source-record-aliases-v1"
    records = data["records"]
    assert len({r["record_alias"] for r in records}) == len(records)
    canonical_ids = {r["canonical_id"] for r in records}
    assert not canonical_ids & {r["record_alias"] for r in records}, "Evidence aliases must point directly to a canonical source"

    def evidence(spec):
        path = (ROOT / spec["path"]).resolve()
        assert path.is_relative_to(ROOT)
        rows = json.loads(path.read_text())[spec["records_key"]]
        matches = [r for r in rows if r["id"] == spec["record_id"]]
        assert len(matches) == 1, spec["record_id"]

        def field(keys):
            value = matches[0]
            for key in keys:
                value = value[key]
            return value

        literal = field(spec["literal_fields"])
        assert isinstance(literal, str) and not any(c.isspace() for c in literal)
        return literal, (field(spec["printed_page_fields"]), field(spec["source_section_fields"]))

    for record in records:
        alias = record["record_alias"]
        assert record["canonical_id"] != alias
        assert record["canonical_evidence"]["record_id"] == record["canonical_id"]
        assert record["alias_evidence"]["record_id"] == alias
        first, first_location = evidence(record["canonical_evidence"])
        later, later_location = evidence(record["alias_evidence"])
        location = (record["printed_page"], record["source_section"])
        assert first_location == later_location == location, (alias, "source locations differ")
        assert first == later and len(first) == record["source_slots"], (alias, "literal sources differ")
        assert hashlib.sha256(first.encode()).hexdigest() == record["literal_source_sha256"], alias
        assert source_exists(ROOT / record["canonical_case_path"])
        paths = record["evidence_paths"]
        assert paths and len(paths) == len(set(paths)), alias
        assert record["alias_evidence"]["path"] in paths, alias
        assert all((ROOT / path).is_file() for path in paths), alias
    return records


def evidence_record_id(row, evidence_path, aliases=None):
    """Resolve a specifically registered evidence identifier for one case.

    There is no global spelling substitution or first-record fallback. A legacy
    identifier is usable only on the exact canonical row and evidence path.
    """
    requested = row.get("evidence_record_ids", {}).get(evidence_path, row["id"])
    if requested == row["id"]:
        return requested
    assert evidence_path in row.get("evidence", []), (row["id"], "Alias path is not cited")
    aliases = source_record_aliases() if aliases is None else aliases
    matching = [r for r in aliases if r["canonical_id"] == row["id"]
                and r["record_alias"] == requested and evidence_path in r["evidence_paths"]]
    assert len(matching) == 1, (row["id"], requested, "Unregistered evidence alias")
    return requested


def physical_source_accounting(catalogue):
    """Enforce exactly one live catalogue entry per physical source."""
    locations = source_locations(catalogue)
    rows = {r["id"]: r for group in ("challenge", "other") for r in catalogue[group]}
    by_location = defaultdict(set)
    for ident, location in locations.items():
        by_location[location].add(ident)
    for location, identifiers in by_location.items():
        assert len(identifiers) == 1, f"Duplicate physical source at p{location[0]} {location[1]}: {sorted(identifiers)}"
    challenge_locations = {locations[r["id"]] for r in catalogue["challenge"]}
    other_locations = {locations[r["id"]] for r in catalogue["other"]}
    unique = challenge_locations | other_locations
    assert len(rows) == len(unique), "Every catalogue entry must have one distinct physical source"
    return {"catalogue_entries": len(rows), "reviewed_entries": len(rows),
            "challenge_entries": len(catalogue["challenge"]),
            "other_reviewed_entries": len(catalogue["other"]),
            "unique_physical_sources": len(unique),
            "challenge_physical_sources": len(challenge_locations),
            "other_unique_physical_sources": len(other_locations),
            "additional_physical_sources": len(other_locations - challenge_locations),
            "state_counts": {state: sum(r.get("state") == state for r in rows.values()) for state in STATES},
            "canonical_source_ids": {ident: ident for ident in rows}, "locations": locations}


def load_catalog():
    data = json.loads(DATA.read_text())
    assert data["schema"] == "adfgvx-reading-catalog-v2"
    assert set(data["state_definitions"]) == set(STATES)
    source_ids = set(source_messages())
    assert {r["id"] for r in data["challenge"]} == source_ids
    assert len(data["challenge"]) == 22
    seen = set()
    for group in ("challenge", "other"):
        for row in data[group]:
            assert row["id"] not in seen, row["id"]
            seen.add(row["id"])
            assert row["state"] in STATES, (row["id"], "Unknown catalogue state")
            for field in ("label", "subject", "status", "credit", "path"):
                assert isinstance(row[field], str) and row[field].strip(), (row["id"], field)
                assert "\n" not in row[field] and "|" not in row[field], (row["id"], field)
            path = row["path"].split("#")[0]
            assert source_exists(ROOT / path), path
            for evidence in row.get("evidence", []):
                assert (ROOT / evidence).is_file(), evidence
            if group == "other":
                assert row["source_reviewed"] is True, row["id"]
                assert row["id"] not in source_ids
                assert isinstance(row["printed_page"], int) and row["printed_page"] > 0, row["id"]
    accounting = physical_source_accounting(data)
    census = json.loads(SOURCE_CENSUS.read_text())
    expected = {(page["printed_page"], section) for page in census["log_pages"]
                for section in page["ciphertext_body_sections"]}
    actual = set(accounting["locations"].values())
    assert actual == expected, ("Catalogue must cover every reviewed physical source exactly once",
                                "missing", sorted(expected - actual), "extra", sorted(actual - expected))
    aliases = source_record_aliases()
    records = {row["id"]: row for group in ("challenge", "other") for row in data[group]}
    for alias in aliases:
        canonical, old = alias["canonical_id"], alias["record_alias"]
        assert old not in records, (old, "An evidence alias cannot be a catalogue entry")
        assert canonical in records, (canonical, "Canonical entry is missing")
        row = records[canonical]
        assert row["path"] == alias["canonical_case_path"]
        assert row["prior_reading_credit"] == alias["prior_reading_credit"]
        assert accounting["locations"][canonical] == (alias["printed_page"], alias["source_section"])
    for row in records.values():
        for path in row.get("evidence_record_ids", {}):
            assert path in row.get("evidence", []), (row["id"], "Alias path is not cited")
            evidence_record_id(row, path, aliases)
    return data


def relative_link(path, destination):
    relative_dir = destination.parent.relative_to(ROOT).as_posix()
    file, separator, anchor = path.partition("#")
    link = posixpath.relpath(file, relative_dir)
    return link + ("#" + anchor if separator else "")


def table(rows, destination):
    lines = ["| Source | State | Subject |", "|---|---|---|"]
    for row in rows:
        link = relative_link(source_target(row), destination)
        assert row["state"] in STATES, row["id"]
        lines.append(f"| [{row['label']}]({link}) | {row['state']} | {row['subject']} |")
    return "\n".join(lines)


def source_target(row):
    page = row.get('printed_page')
    if page is None:
        page = source_messages()[row['id']]['source']['printed_page']
    anchor = 'source-' + re.sub(r'[^a-z0-9]+', '-', row['id'].lower()).strip('-')
    return f"cases/pages/{page:03d}.md#{anchor}"


def natural_key(value):
    return tuple((1, int(part)) if part.isdigit() else (0, part.lower())
                 for part in re.split(r"(\d+)", value))


def page_groups(data):
    """Place each canonical source once, retaining original challenge metadata."""
    physical_source_accounting(data)
    messages = source_messages()
    pages = defaultdict(lambda: {"challenge": [], "other": []})
    for group in ("challenge", "other"):
        for row in data[group]:
            page = (messages[row["id"]]["source"]["printed_page"]
                    if group == "challenge" else row["printed_page"])
            assert isinstance(page, int) and page > 0, row["id"]
            pages[page][group].append(row)
    for groups in pages.values():
        for rows in groups.values():
            rows.sort(key=lambda r: (natural_key(r.get("source_section", r["id"])),
                                     natural_key(r["id"])))
    # Guard both against losing a record and against listing one in two pages.
    for group in ("challenge", "other"):
        expected = Counter(row["id"] for row in data[group])
        actual = Counter(row["id"] for groups in pages.values() for row in groups[group])
        assert actual == expected and all(n == 1 for n in actual.values()), group
    return dict(sorted(pages.items()))


def band_start(page):
    return page // PAGE_BAND_SIZE * PAGE_BAND_SIZE


def band_label(pages, start, group=None):
    """Label the pages actually listed; directory bands remain stable."""
    members = [page for page in band_pages(pages, start)
               if group is None or pages[page][group]]
    assert members, (start, group)
    first, last = min(members), max(members)
    return f"p. {first}" if first == last else f"pp. {first}–{last}"


def band_path(start):
    return f"cases/pages/{start:03d}-{start + PAGE_BAND_SIZE - 1:03d}/README.md"


def band_pages(pages, start):
    return [page for page in pages if band_start(page) == start]


def band_rows(pages, start, group):
    return [row for page in band_pages(pages, start) for row in pages[page][group]]


def bands(pages):
    return sorted({band_start(page) for page in pages})


def compact_table(pages, destination):
    lines = ['| Printed pages | Sources |', '|---|---:|']
    for start in bands(pages):
        count = sum(len(band_rows(pages, start, group)) for group in ('challenge', 'other'))
        link = relative_link(band_path(start), destination)
        lines.append(f"| [{band_label(pages, start)}]({link}) | {count} |")
    return '\n'.join(lines)


def render(data, destination, pages=None):
    pages = page_groups(data) if pages is None else pages
    return '\n'.join([START, '## Browse by printed page', '',
        'Choose a range to see its pages and message subjects. Each page opens its complete ciphertexts, readings and source explanations.', '',
        compact_table(pages, destination), '', END])


def render_page_index(data, pages):
    destination = PAGE_ROOT / 'README.md'
    return '\n'.join(['# Browse by printed page', '', GENERATED, '',
        '[ADFGVX Cipher](../../README.md) · [Browse by subject](../../topics/README.md) · [Historical research](../../docs/historical-studies/README.md)', '',
        'Choose a range for its page-and-subject table. Each page opens a complete source edition.', '',
        compact_table(pages, destination), '',
        '[Reading conventions](../../docs/reading-conventions.md) · [Source identity](../../docs/catalogue-source-identity.md)', ''])


def render_band(data, pages, start):
    destination = ROOT / band_path(start)
    members = band_pages(pages, start)
    starts = bands(pages)
    at = starts.index(start)
    nav = ['[All page ranges](../README.md)', '[Browse by subject](../../../topics/README.md)']
    if at:
        previous = starts[at - 1]
        nav.append(f"[← {band_label(pages, previous)}]({relative_link(band_path(previous), destination)})")
    if at + 1 < len(starts):
        following = starts[at + 1]
        nav.append(f"[{band_label(pages, following)} →]({relative_link(band_path(following), destination)})")
    locations = source_locations(data)
    lines = [f'# Childs {band_label(pages, start)}', '', GENERATED, '', ' · '.join(nav), '',
             '| Page | Messages and subjects |', '|---|---|']
    for page in members:
        edition = relative_link(f'cases/pages/{page:03d}.md', destination)
        rows = sorted(pages[page]['challenge'] + pages[page]['other'],
                      key=lambda row: natural_key(locations[row['id']][1]))
        subjects = []
        for row in rows:
            link = relative_link(source_target(row), destination)
            state = ' **OPEN**' if row['state'] == 'OPEN' else ''
            subjects.append(f"[{row['label']}]({link}){state} — {row['subject']}")
        lines.append(f'| <a id="p{page}"></a>[{page}]({edition}) | {"<br>".join(subjects)} |')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated guides, page coverage and local links without writing")
    args = parser.parse_args()
    data = load_catalog()
    pages = page_groups(data)
    generated = {PAGE_ROOT / "README.md": render_page_index(data, pages)}
    generated.update({ROOT / band_path(start): render_band(data, pages, start) for start in bands(pages)})
    for path in (ROOT / "README.md",):
        current = path.read_text()
        assert current.count(START) == current.count(END) == 1, path
        before, rest = current.split(START)
        _, after = rest.split(END)
        generated[path] = before + render(data, path, pages) + after
    stale = {path for path in PAGE_ROOT.glob("*/README.md")
             if "<!-- Generated by python -m adfgvx.catalog;" in path.read_text()} - set(generated)
    assert not stale, "Obsolete generated page ranges: " + ", ".join(str(p.relative_to(ROOT)) for p in sorted(stale))
    for path, expected in generated.items():
        if args.check:
            assert path.is_file() and path.read_text() == expected, f"Regenerate {path.relative_to(ROOT)} with python -m adfgvx.catalog"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    # Reuse the navigation check for relative file targets and GitHub section slugs.
    # The import is local because navigation itself uses the shared table renderer.
    from .navigation import check_links
    checked = check_links(set(generated))
    counts = physical_source_accounting(data)
    print(f"Catalogue: {counts['catalogue_entries']} physical sources, one entry each; "
          f"{counts['state_counts']['OPEN']} OPEN; "
          f"{len(pages)} source pages across {len(bands(pages))} page ranges; "
          f"{checked} local links and sections checked.")


if __name__ == "__main__":
    main()
