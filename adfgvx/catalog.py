"""Build compact reading guides and page-number indexes from one catalogue.

ADFGVX Cipher — icekylinx and GPT-6 Astra Pro.
This indexes reviewed readings; uninspected OCR candidates are not admitted.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import hashlib
import json
import posixpath
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/reading_catalog.json"
STATUS_DISPLAY = ROOT / "data/catalog_status_display.json"
SOURCE_OVERLAPS = ROOT / "data/catalog_source_overlaps.json"
START = "<!-- READING-CATALOG:START -->"
END = "<!-- READING-CATALOG:END -->"
PAGE_ROOT = ROOT / "cases/pages"
PAGE_BAND_SIZE = 25
GENERATED = "<!-- Generated by python -m adfgvx.catalog; edit data/reading_catalog.json, data/catalog_status_display.json and data/catalog_source_overlaps.json. -->"


def source_messages():
    return {m["id"]: m for m in json.loads((ROOT / "data/messages.json").read_text())["messages"]}


def source_locations(catalogue):
    """Return exact physical locations without equating similar message bodies."""
    messages = source_messages()
    locations = {}
    for group in ("challenge", "other"):
        for row in catalogue[group]:
            if group == "challenge":
                source = messages[row["id"]]["source"]
                page, section = source["printed_page"], source["section"]
            else:
                page, section = row["printed_page"], row["source_section"]
            assert isinstance(page, int) and page > 0, row["id"]
            assert isinstance(section, str) and section and section == section.strip(), row["id"]
            assert row["id"] not in locations, row["id"]
            locations[row["id"]] = (page, section)
    return locations


def source_overlap_register():
    """Verify the literal evidence behind each registered same-source edition."""
    data = json.loads(SOURCE_OVERLAPS.read_text())
    assert data["schema"] == "adfgvx-catalog-source-overlaps-v1"
    records = data["records"]
    assert len({r["edition_id"] for r in records}) == len(records)
    canonical_ids = {r["canonical_id"] for r in records}
    assert not canonical_ids & {r["edition_id"] for r in records}, "Overlaps must point directly to a canonical source"

    def evidence(spec):
        path = (ROOT / spec["path"]).resolve()
        assert path.is_relative_to(ROOT)
        rows = json.loads(path.read_text())[spec["records_key"]]
        matches = [r for r in rows if r["id"] == spec["record_id"]]
        assert len(matches) == 1, spec["record_id"]

        def field(keys):
            value = matches[0]
            for key in keys:
                value = value[key]
            return value

        literal = field(spec["literal_fields"])
        assert isinstance(literal, str) and not any(c.isspace() for c in literal)
        return literal, (field(spec["printed_page_fields"]), field(spec["source_section_fields"]))

    for record in records:
        assert record["canonical_id"] != record["edition_id"]
        assert record["canonical_evidence"]["record_id"] == record["canonical_id"]
        assert record["edition_evidence"]["record_id"] == record["edition_id"]
        first, first_location = evidence(record["canonical_evidence"])
        later, later_location = evidence(record["edition_evidence"])
        location = (record["printed_page"], record["source_section"])
        assert first_location == later_location == location, (record["edition_id"], "source locations differ")
        assert first == later and len(first) == record["source_slots"], (record["edition_id"], "literal sources differ")
        assert hashlib.sha256(first.encode()).hexdigest() == record["literal_source_sha256"], record["edition_id"]
        assert (ROOT / record["canonical_case_path"]).is_file()
    return records


def physical_source_accounting(catalogue, *, require_all_registered=False):
    """Count entries and sources separately, rejecting undeclared location aliases.

    Historical snapshots may predate a later edition. The live loader requires
    every registered edition; either mode rejects an unregistered collision.
    """
    locations = source_locations(catalogue)
    rows = {r["id"]: r for group in ("challenge", "other") for r in catalogue[group]}
    canonical = {ident: ident for ident in rows}
    registered = defaultdict(set)
    active = []
    for overlap in source_overlap_register():
        first, later = overlap["canonical_id"], overlap["edition_id"]
        location = (overlap["printed_page"], overlap["source_section"])
        registered[location].update((first, later))
        if require_all_registered:
            assert first in rows and later in rows, (later, "registered edition is missing")
        for ident in (first, later):
            if ident in locations:
                assert locations[ident] == location, (ident, "registered source location changed")
        if first in rows:
            assert rows[first]["path"] == overlap["canonical_case_path"]
            assert rows[first]["credit"] == overlap["canonical_credit"]
        if later in rows:
            assert first in rows, (later, "canonical source entry is missing")
            canonical[later] = first
            active.append({"canonical_id": first, "edition_id": later,
                           "printed_page": location[0], "source_section": location[1]})
    by_location = defaultdict(set)
    for ident, location in locations.items():
        by_location[location].add(ident)
    for location, identifiers in by_location.items():
        if len(identifiers) > 1:
            allowed = registered[location] & rows.keys()
            assert identifiers == allowed, f"Unregistered physical-source overlap at p{location[0]} {location[1]}: {sorted(identifiers)}"
    challenge_locations = {locations[r["id"]] for r in catalogue["challenge"]}
    other_locations = {locations[r["id"]] for r in catalogue["other"]}
    unique = challenge_locations | other_locations
    assert len(set(canonical.values())) == len(unique), "Physical-source identities are inconsistent"
    return {"reviewed_entries": len(rows), "challenge_entries": len(catalogue["challenge"]),
            "other_reviewed_entries": len(catalogue["other"]),
            "unique_physical_sources": len(unique),
            "challenge_physical_sources": len(challenge_locations),
            "other_unique_physical_sources": len(other_locations),
            "additional_physical_sources": len(other_locations - challenge_locations),
            "later_edition_entries": len(rows) - len(unique),
            "canonical_source_ids": canonical, "locations": locations,
            "registered_overlaps": active}


def load_catalog():
    data = json.loads(DATA.read_text())
    source_ids = set(source_messages())
    assert {r["id"] for r in data["challenge"]} == source_ids
    assert len(data["challenge"]) == 22
    seen = set()
    for group in ("challenge", "other"):
        for row in data[group]:
            assert row["id"] not in seen, row["id"]
            seen.add(row["id"])
            for field in ("label", "subject", "status", "credit", "path"):
                assert isinstance(row[field], str) and row[field].strip(), (row["id"], field)
                assert "\n" not in row[field] and "|" not in row[field], (row["id"], field)
            path = row["path"].split("#")[0]
            assert (ROOT / path).is_file(), path
            for evidence in row.get("evidence", []):
                assert (ROOT / evidence).is_file(), evidence
            if group == "other":
                assert row["source_reviewed"] is True, row["id"]
                assert row["id"] not in source_ids
                assert isinstance(row["printed_page"], int) and row["printed_page"] > 0, row["id"]
    # Historical catalogue rows are frozen evidence. A small, reviewed display
    # register corrects count units and spacing without rewriting those rows.
    status_displays(data)
    physical_source_accounting(data, require_all_registered=True)
    return data


def status_displays(catalogue=None):
    register = json.loads(STATUS_DISPLAY.read_text())
    rows = register["records"]
    assert len({row["id"] for row in rows}) == len(rows)
    if catalogue is not None:
        records = {row["id"]: row for group in ("challenge", "other")
                   for row in catalogue[group]}
        for row in rows:
            assert records[row["id"]]["status"] == row["source_status"], row["id"]
    for row in rows:
        before, after = row["source_status"], row["display_status"]
        assert before != after and after.strip() == after
        assert "\n" not in after and "|" not in after
        assert re.findall(r"\d+", before) == re.findall(r"\d+", after), row["id"]
    return {row["id"]: row for row in rows}


def relative_link(path, destination):
    relative_dir = destination.parent.relative_to(ROOT).as_posix()
    file, separator, anchor = path.partition("#")
    link = posixpath.relpath(file, relative_dir)
    return link + ("#" + anchor if separator else "")


def table(rows, destination):
    displays = status_displays()
    overlaps = {r["edition_id"]: r for r in source_overlap_register()}
    lines = ["| Ciphertext | Most likely content | Reading status | Reading or review credit |",
             "|---|---|---|---|"]
    for row in rows:
        link = relative_link(row["path"], destination)
        correction = displays.get(row["id"])
        if correction:
            assert correction["source_status"] == row["status"], row["id"]
        status = correction["display_status"] if correction else row["status"]
        credit = row["credit"]
        if row["id"] in overlaps:
            overlap = overlaps[row["id"]]
            original = relative_link(overlap["canonical_case_path"], destination)
            status += f"; later edition of [{overlap['canonical_id']}]({original})"
            credit += f"; original reading: [{overlap['canonical_credit']}]({original})"
        lines.append(f"| [{row['label']}]({link}) | {row['subject']} | {status} | {credit} |")
    return "\n".join(lines)


def natural_key(value):
    return tuple((1, int(part)) if part.isdigit() else (0, part.lower())
                 for part in re.split(r"(\d+)", value))


def page_groups(data):
    """Place each edition entry once, using source metadata for challenges."""
    physical_source_accounting(data)
    messages = source_messages()
    pages = defaultdict(lambda: {"challenge": [], "other": []})
    for group in ("challenge", "other"):
        for row in data[group]:
            page = (messages[row["id"]]["source"]["printed_page"]
                    if group == "challenge" else row["printed_page"])
            assert isinstance(page, int) and page > 0, row["id"]
            pages[page][group].append(row)
    for groups in pages.values():
        for rows in groups.values():
            rows.sort(key=lambda r: (natural_key(r.get("source_section", r["id"])),
                                     natural_key(r["id"])))
    # Guard both against losing a record and against listing one in two pages.
    for group in ("challenge", "other"):
        expected = Counter(row["id"] for row in data[group])
        actual = Counter(row["id"] for groups in pages.values() for row in groups[group])
        assert actual == expected and all(n == 1 for n in actual.values()), group
    return dict(sorted(pages.items()))


def band_start(page):
    return page // PAGE_BAND_SIZE * PAGE_BAND_SIZE


def band_label(pages, start, group=None):
    """Label the pages actually listed; directory bands remain stable."""
    members = [page for page in band_pages(pages, start)
               if group is None or pages[page][group]]
    assert members, (start, group)
    first, last = min(members), max(members)
    return f"p. {first}" if first == last else f"pp. {first}–{last}"


def band_path(start):
    return f"cases/pages/{start:03d}-{start + PAGE_BAND_SIZE - 1:03d}/README.md"


def band_pages(pages, start):
    return [page for page in pages if band_start(page) == start]


def band_rows(pages, start, group):
    return [row for page in band_pages(pages, start) for row in pages[page][group]]


def bands(pages):
    return sorted({band_start(page) for page in pages})


def compact_table(pages, destination, group):
    if group == "challenge":
        lines = ["| Printed source pages | Entries | Challenge identifiers |", "|---|---:|---|"]
    else:
        lines = ["| Printed source pages | Reviewed entries |", "|---|---:|"]
    for start in bands(pages):
        rows = band_rows(pages, start, group)
        if not rows:
            continue
        link = relative_link(band_path(start), destination)
        label = band_label(pages, start, group)
        if group == "challenge":
            detail = ", ".join(f"[{row['label']}]({relative_link(row['path'], destination)})" for row in rows)
            lines.append(f"| [{label}]({link}) | {len(rows)} | {detail} |")
        else:
            lines.append(f"| [{label}]({link}) | {len(rows)} |")
    return "\n".join(lines)


def render(data, destination, pages=None):
    pages = page_groups(data) if pages is None else pages
    counts = physical_source_accounting(data)
    index = relative_link("cases/pages/README.md", destination)
    overlap_note = relative_link("docs/catalogue-source-overlaps.md", destination)
    lines = [
        START,
        "## Browse by source page", "",
        f"Page numbers refer to the printed Childs volume. Choose a range below or [open the complete page index]({index}).", "",
        "### The 22 challenge entries", "",
        "Original challenge identifiers are retained; p198 denotes section D.", "",
        compact_table(pages, destination, "challenge"), "",
        f"### Other ciphertexts — {len(data['other'])} reviewed entries", "",
        "Numbered parts and separately received copies have their own entries.", "",
        f"**{counts['reviewed_entries']} catalogue entries from {counts['unique_physical_sources']} source bodies.** The [source register]({overlap_note}) identifies {counts['later_edition_entries']} additional edition of an already listed source.", "",
        compact_table(pages, destination, "other"), "",
        "Source review and current research: **icekylinx and GPT-6 Astra Pro**. Each detailed entry credits its earlier readings and keys.",
        END,
    ]
    return "\n".join(lines)


def render_page_index(data, pages):
    destination = PAGE_ROOT / "README.md"
    counts = physical_source_accounting(data)
    lines = [
        "# Readings by source page", "", GENERATED, "",
        "[ADFGVX Cipher](../../README.md) · [Browse by topic](../README.md#browse-by-topic) · [Reading conventions](../../docs/reading-conventions.md)", "",
        f"**22 challenge entries and {len(data['other'])} other reviewed entries from {counts['unique_physical_sources']} source bodies.** Choose a range or jump directly to a page.", "",
        "Page numbers refer to the printed Childs volume. Each page lists the messages, reading status, credits and links to the complete editions.", "",
        "| Printed source pages | Challenge entries | Other reviewed entries | Jump to an individual page |",
        "|---|---:|---:|---|",
    ]
    for start in bands(pages):
        link = relative_link(band_path(start), destination)
        page_links = " · ".join(f"[p{page}]({link}#p{page})" for page in band_pages(pages, start))
        lines.append(f"| [{band_label(pages, start)}]({link}) | {len(band_rows(pages, start, 'challenge'))} | {len(band_rows(pages, start, 'other'))} | {page_links} |")
    lines.extend([
        "", "## Reading status and credit", "",
        "Challenge and other reviewed records have separate tables under each printed page. Each case supplies readable text, raw and edited outputs, source evidence and credits.", "",
        "The [source register](../../docs/catalogue-source-overlaps.md) verifies entry and physical-source totals. Repeated transmissions and numbered parts retain their separate source locations.", "",
        "Research and editorial work: **icekylinx and GPT-6 Astra Pro**.", "",
    ])
    return "\n".join(lines)


def render_band(data, pages, start):
    destination = ROOT / band_path(start)
    members = band_pages(pages, start)
    starts = bands(pages)
    at = starts.index(start)
    nav = ["[All source pages](../README.md)", "[Browse by topic](../../README.md#browse-by-topic)",
           "[Reading conventions](../../../docs/reading-conventions.md)"]
    if at:
        previous = starts[at - 1]
        nav.append(f"[← {band_label(pages, previous)}]({relative_link(band_path(previous), destination)})")
    if at + 1 < len(starts):
        following = starts[at + 1]
        nav.append(f"[{band_label(pages, following)} →]({relative_link(band_path(following), destination)})")
    n_challenge = len(band_rows(pages, start, "challenge"))
    n_other = len(band_rows(pages, start, "other"))
    locations = source_locations(data)
    band_entries = [r for group in ("challenge", "other") for r in band_rows(pages, start, group)]
    n_sources = len({locations[r["id"]] for r in band_entries})
    lines = [
        f"# Readings from {band_label(pages, start)}", "", GENERATED, "",
        " · ".join(nav), "",
        f"**{n_challenge} challenge {'entry' if n_challenge == 1 else 'entries'} · {n_other} other reviewed entries · {len(members)} printed pages · {n_sources} physical sources.**", "",
        "Jump to page: " + " · ".join(f"[p{page}](#p{page})" for page in members) + ".", "",
        "Page numbers refer to the printed Childs volume. Each row links to the complete reading and its evidence.", "",
    ]
    for page in members:
        lines.extend([f"## p{page}", ""])
        for group, label in (("challenge", "Challenge entries"), ("other", "Other reviewed source records")):
            rows = pages[page][group]
            if rows:
                lines.extend([f"### {label}", "", table(rows, destination), ""])
    lines.extend(["[Return to all source pages](../README.md).", "",
                  "Research and editorial work: **icekylinx and GPT-6 Astra Pro**.", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated guides, page coverage and local links without writing")
    args = parser.parse_args()
    data = load_catalog()
    pages = page_groups(data)
    generated = {PAGE_ROOT / "README.md": render_page_index(data, pages)}
    generated.update({ROOT / band_path(start): render_band(data, pages, start) for start in bands(pages)})
    for path in (ROOT / "README.md", ROOT / "cases/README.md"):
        current = path.read_text()
        assert current.count(START) == current.count(END) == 1, path
        before, rest = current.split(START)
        _, after = rest.split(END)
        generated[path] = before + render(data, path, pages) + after
    stale = {path for path in PAGE_ROOT.glob("*/README.md")
             if "<!-- Generated by python -m adfgvx.catalog;" in path.read_text()} - set(generated)
    assert not stale, "Obsolete generated page ranges: " + ", ".join(str(p.relative_to(ROOT)) for p in sorted(stale))
    for path, expected in generated.items():
        if args.check:
            assert path.is_file() and path.read_text() == expected, f"Regenerate {path.relative_to(ROOT)} with python -m adfgvx.catalog"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    # Reuse the navigation check for relative file targets and GitHub section slugs.
    # The import is local because navigation itself uses the shared table renderer.
    from .navigation import check_links
    checked = check_links(set(generated))
    counts = physical_source_accounting(data)
    print(f"Catalogue: 22 challenge entries and {len(data['other'])} other reviewed entries; "
          f"{counts['unique_physical_sources']} unique physical sources, {counts['additional_physical_sources']} beyond the challenge set; "
          f"each entry appears once in {len(pages)} source pages across {len(bands(pages))} page ranges; "
          f"{checked} local links and sections checked.")


if __name__ == "__main__":
    main()
