"""Build compact reading guides and page-number indexes from one catalogue.

ADFGVX Cipher — icekylinx and GPT-6 Astra Pro.
This indexes reviewed readings; uninspected OCR candidates are not admitted.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import json
import posixpath
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/reading_catalog.json"
STATUS_DISPLAY = ROOT / "data/catalog_status_display.json"
START = "<!-- READING-CATALOG:START -->"
END = "<!-- READING-CATALOG:END -->"
PAGE_ROOT = ROOT / "cases/pages"
PAGE_BAND_SIZE = 25
GENERATED = "<!-- Generated by python -m adfgvx.catalog; edit data/reading_catalog.json and data/catalog_status_display.json. -->"


def source_messages():
    return {m["id"]: m for m in json.loads((ROOT / "data/messages.json").read_text())["messages"]}


def load_catalog():
    data = json.loads(DATA.read_text())
    source_ids = set(source_messages())
    assert {r["id"] for r in data["challenge"]} == source_ids
    assert len(data["challenge"]) == 22
    seen = set()
    for group in ("challenge", "other"):
        for row in data[group]:
            assert row["id"] not in seen, row["id"]
            seen.add(row["id"])
            for field in ("label", "subject", "status", "credit", "path"):
                assert isinstance(row[field], str) and row[field].strip(), (row["id"], field)
                assert "\n" not in row[field] and "|" not in row[field], (row["id"], field)
            path = row["path"].split("#")[0]
            assert (ROOT / path).is_file(), path
            for evidence in row.get("evidence", []):
                assert (ROOT / evidence).is_file(), evidence
            if group == "other":
                assert row["source_reviewed"] is True, row["id"]
                assert row["id"] not in source_ids
                assert isinstance(row["printed_page"], int) and row["printed_page"] > 0, row["id"]
    # Historical catalogue rows are frozen evidence. A small, reviewed display
    # register corrects count units and spacing without rewriting those rows.
    status_displays(data)
    return data


def status_displays(catalogue=None):
    register = json.loads(STATUS_DISPLAY.read_text())
    rows = register["records"]
    assert len({row["id"] for row in rows}) == len(rows)
    if catalogue is not None:
        records = {row["id"]: row for group in ("challenge", "other")
                   for row in catalogue[group]}
        for row in rows:
            assert records[row["id"]]["status"] == row["source_status"], row["id"]
    for row in rows:
        before, after = row["source_status"], row["display_status"]
        assert before != after and after.strip() == after
        assert "\n" not in after and "|" not in after
        assert re.findall(r"\d+", before) == re.findall(r"\d+", after), row["id"]
    return {row["id"]: row for row in rows}


def relative_link(path, destination):
    relative_dir = destination.parent.relative_to(ROOT).as_posix()
    file, separator, anchor = path.partition("#")
    link = posixpath.relpath(file, relative_dir)
    return link + ("#" + anchor if separator else "")


def table(rows, destination):
    displays = status_displays()
    lines = ["| Ciphertext | Most likely content | Reading status | Reading or review credit |",
             "|---|---|---|---|"]
    for row in rows:
        link = relative_link(row["path"], destination)
        correction = displays.get(row["id"])
        if correction:
            assert correction["source_status"] == row["status"], row["id"]
        status = correction["display_status"] if correction else row["status"]
        lines.append(f"| [{row['label']}]({link}) | {row['subject']} | {status} | {row['credit']} |")
    return "\n".join(lines)


def natural_key(value):
    return tuple((1, int(part)) if part.isdigit() else (0, part.lower())
                 for part in re.split(r"(\d+)", value))


def page_groups(data):
    """Place each physical record once, using source metadata for challenges."""
    messages = source_messages()
    pages = defaultdict(lambda: {"challenge": [], "other": []})
    for group in ("challenge", "other"):
        for row in data[group]:
            page = (messages[row["id"]]["source"]["printed_page"]
                    if group == "challenge" else row["printed_page"])
            assert isinstance(page, int) and page > 0, row["id"]
            pages[page][group].append(row)
    for groups in pages.values():
        for rows in groups.values():
            rows.sort(key=lambda r: (natural_key(r.get("source_section", r["id"])),
                                     natural_key(r["id"])))
    # Guard both against losing a record and against listing one in two pages.
    for group in ("challenge", "other"):
        expected = Counter(row["id"] for row in data[group])
        actual = Counter(row["id"] for groups in pages.values() for row in groups[group])
        assert actual == expected and all(n == 1 for n in actual.values()), group
    return dict(sorted(pages.items()))


def band_start(page):
    return page // PAGE_BAND_SIZE * PAGE_BAND_SIZE


def band_label(start):
    return f"pp. {start}–{start + PAGE_BAND_SIZE - 1}"


def band_path(start):
    return f"cases/pages/{start:03d}-{start + PAGE_BAND_SIZE - 1:03d}/README.md"


def band_pages(pages, start):
    return [page for page in pages if band_start(page) == start]


def band_rows(pages, start, group):
    return [row for page in band_pages(pages, start) for row in pages[page][group]]


def bands(pages):
    return sorted({band_start(page) for page in pages})


def compact_table(pages, destination, group):
    if group == "challenge":
        lines = ["| Printed source pages | Entries | Challenge identifiers |", "|---|---:|---|"]
    else:
        lines = ["| Printed source pages | Reviewed records | Pages represented |", "|---|---:|---:|"]
    for start in bands(pages):
        rows = band_rows(pages, start, group)
        if not rows:
            continue
        link = relative_link(band_path(start), destination)
        if group == "challenge":
            detail = ", ".join(f"[{row['label']}]({relative_link(row['path'], destination)})" for row in rows)
        else:
            detail = str(sum(bool(pages[page][group]) for page in band_pages(pages, start)))
        lines.append(f"| [{band_label(start)}]({link}) | {len(rows)} | {detail} |")
    return "\n".join(lines)


def render(data, destination, pages=None):
    pages = page_groups(data) if pages is None else pages
    index = relative_link("cases/pages/README.md", destination)
    lines = [
        START,
        "## Browse by source page", "",
        f"[Open the complete page index]({index}). The page ranges below lead to short tables for each printed manuscript page, with each record's content, status and credit.", "",
        "### The 22 challenge entries", "",
        "These retain all original challenge identifiers. Page numbers alone do not identify a message: p198 is section D, while p198 B/C/E are separate records.", "",
        compact_table(pages, destination, "challenge"), "",
        f"### Other ciphertexts — {len(data['other'])} reviewed records", "",
        "Multipart messages and repeated transmissions have separate source records even when they share a case page. Direct readings, source-supported reconstructions and conjectural repairs keep their stated limits in the detailed page tables.", "",
        compact_table(pages, destination, "other"), "",
        "The catalogue covers source-reviewed records with published reading evidence; the wider OCR search pool contains additional unreviewed ciphertext candidates. Earlier authors retain their credits. Current source review and new research use **icekylinx and GPT-6 Astra Pro**; a review credit does not assert first-decipherment priority.",
        END,
    ]
    return "\n".join(lines)


def render_page_index(data, pages):
    destination = PAGE_ROOT / "README.md"
    lines = [
        "# Readings by source page", "", GENERATED, "",
        "[ADFGVX Cipher](../../README.md) · [Browse by topic](../README.md#browse-by-topic) · [Reading conventions](../../docs/reading-conventions.md)", "",
        f"**22 challenge entries and {len(data['other'])} other reviewed source records.** Choose a printed page range, then an individual page. Every record retains its original identifier, reading status, source credit and link to the complete edition.", "",
        "Page numbers refer to the printed Childs collection, not the PDF viewer's page counter. A page can contain several separately identified messages. A multipart message or repeated copy can occur in more than one page range; each physical source record is listed once.", "",
        "| Printed source pages | Challenge entries | Other reviewed records | Jump to an individual page |",
        "|---|---:|---:|---|",
    ]
    for start in bands(pages):
        link = relative_link(band_path(start), destination)
        page_links = " · ".join(f"[p{page}]({link}#p{page})" for page in band_pages(pages, start))
        lines.append(f"| [{band_label(start)}]({link}) | {len(band_rows(pages, start, 'challenge'))} | {len(band_rows(pages, start, 'other'))} | {page_links} |")
    lines.extend([
        "", "## Reading status and credit", "",
        "Each range keeps the challenge entries and other reviewed records in separate tables under the relevant source page. The case links lead to the readable text, raw and edited outputs, source qualifications, earlier credits and reproducible evidence.", "",
        "The table counts source records, including repeated transmissions and conditional reconstructions. It is not a count of newly solved ciphertexts. Unreviewed OCR candidates are outside this index.", "",
        "Research and editorial work: **icekylinx and GPT-6 Astra Pro**.", "",
    ])
    return "\n".join(lines)


def render_band(data, pages, start):
    destination = ROOT / band_path(start)
    members = band_pages(pages, start)
    starts = bands(pages)
    at = starts.index(start)
    nav = ["[All source pages](../README.md)", "[Browse by topic](../../README.md#browse-by-topic)",
           "[Reading conventions](../../../docs/reading-conventions.md)"]
    if at:
        previous = starts[at - 1]
        nav.append(f"[← {band_label(previous)}]({relative_link(band_path(previous), destination)})")
    if at + 1 < len(starts):
        following = starts[at + 1]
        nav.append(f"[{band_label(following)} →]({relative_link(band_path(following), destination)})")
    n_challenge = len(band_rows(pages, start, "challenge"))
    n_other = len(band_rows(pages, start, "other"))
    lines = [
        f"# Readings from {band_label(start)}", "", GENERATED, "",
        " · ".join(nav), "",
        f"**{n_challenge} challenge {'entry' if n_challenge == 1 else 'entries'} and {n_other} other reviewed source records across {len(members)} printed pages.** The counts include multipart segments and repeated copies; they do not count first decipherments.", "",
        "Jump to page: " + " · ".join(f"[p{page}](#p{page})" for page in members) + ".", "",
        "Source pages without a reviewed catalogue record are omitted. Each row preserves the catalogue's reading qualifications and credit, with reviewed count-unit and spacing corrections in the displayed status. The linked case explains the evidence and its limits.", "",
    ]
    for page in members:
        lines.extend([f"## p{page}", ""])
        for group, label in (("challenge", "Challenge entries"), ("other", "Other reviewed source records")):
            rows = pages[page][group]
            if rows:
                lines.extend([f"### {label}", "", table(rows, destination), ""])
    lines.extend(["[Return to all source pages](../README.md).", "",
                  "Research and editorial work: **icekylinx and GPT-6 Astra Pro**.", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated guides, page coverage and local links without writing")
    args = parser.parse_args()
    data = load_catalog()
    pages = page_groups(data)
    generated = {PAGE_ROOT / "README.md": render_page_index(data, pages)}
    generated.update({ROOT / band_path(start): render_band(data, pages, start) for start in bands(pages)})
    for path in (ROOT / "README.md", ROOT / "cases/README.md"):
        current = path.read_text()
        assert current.count(START) == current.count(END) == 1, path
        before, rest = current.split(START)
        _, after = rest.split(END)
        generated[path] = before + render(data, path, pages) + after
    stale = {path for path in PAGE_ROOT.glob("*/README.md") if GENERATED in path.read_text()} - set(generated)
    assert not stale, "Obsolete generated page ranges: " + ", ".join(str(p.relative_to(ROOT)) for p in sorted(stale))
    for path, expected in generated.items():
        if args.check:
            assert path.is_file() and path.read_text() == expected, f"Regenerate {path.relative_to(ROOT)} with python -m adfgvx.catalog"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    # Reuse the navigation check for relative file targets and GitHub section slugs.
    # The import is local because navigation itself uses the shared table renderer.
    from .navigation import check_links
    checked = check_links(set(generated))
    print(f"Catalogue: 22 challenge entries and {len(data['other'])} other source-reviewed records; "
          f"each appears once in {len(pages)} source pages across {len(bands(pages))} page ranges; "
          f"{checked} local links and sections checked.")


if __name__ == "__main__":
    main()
