#!/usr/bin/env python3
"""Check the current case structure and visible evidence labels.

Source verifiers import displays() to bind live text to their certificates.
This module checks the present edition, without freezing old prose or layout.
Prepared by icekylinx and GPT-6 Astra Pro. Apache-2.0.
"""
from pathlib import Path
from collections import Counter
import argparse
import hashlib
import json
import os
import re
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
LABELS = {
    "Raw output": "raw_output",
    "Edited output": "edited_output",
    "Readable German": "readable_german",
    "Conditional interpretation": "conditional_interpretation",
    "Source transcription": "source_transcription",
    "Re-encryption witness": "reencryption_witness",
    "Earlier attributed reading": "earlier_attributed_reading",
    "Recomputed prior reading": "recomputed_prior_variant",
    "Search diagnostic": "search_diagnostic",
    "Geometry alternatives": "geometry_alternatives",
    "Meaning": "meaning",
    "English meaning": "meaning",
}
LABEL_PATTERN = re.compile(r"\*\*(" + "|".join(
    re.escape(x) for x in sorted(LABELS, key=len, reverse=True)) + r")\b")


def sha(data):
    return hashlib.sha256(data).hexdigest()


def expected_legend(path):
    """The shared convention link; retained API for source-edition verifiers."""
    link = os.path.relpath(ROOT / "docs/reading-conventions.md", path.parent)
    return "[Reading conventions](" + link + ")"


def preceding_paragraph(lines, start):
    end = start - 1
    while end >= 0 and not lines[end].strip():
        end -= 1
    begin = end
    while begin >= 0 and lines[begin].strip():
        if lines[begin].lstrip().startswith(("```", "~~~")):
            break
        begin -= 1
    return "".join(lines[begin + 1:end + 1]).rstrip("\r\n")


def caption_role(paragraph):
    match = LABEL_PATTERN.search(paragraph)
    return LABELS[match.group(1)] if match else None


def displays(text):
    """Return complete fenced records and explicit Markdown quote displays."""
    lines = text.splitlines(keepends=True)
    fences, quotes = [], []
    number = 0
    while number < len(lines):
        line = lines[number]
        opening = re.match(r"^ {0,3}(`{3,}|~{3,})([^\r\n]*)", line)
        if opening:
            marker, language = opening.group(1), opening.group(2).strip()
            end = number + 1
            close = re.compile(r"^ {0,3}" + re.escape(marker[0]) + "{" +
                               str(len(marker)) + r",}[ \t]*(?:\r?\n)?$")
            while end < len(lines) and not close.fullmatch(lines[end]):
                end += 1
            if end == len(lines):
                raise ValueError("Unterminated fence at line " + str(number + 1))
            complete = "".join(lines[number:end + 1])
            body = "".join(lines[number + 1:end])
            paragraph = preceding_paragraph(lines, number)
            role = caption_role(paragraph)
            if role is None and (language in ("sh", "shell", "bash") or
                                 body.lstrip().startswith(("python ", "python3 "))):
                role = "reproduction_command"
            fences.append({"index": len(fences), "line": number + 1,
                           "sha256": sha(complete.encode()),
                           "body_sha256": sha(body.rstrip("\r\n").encode()),
                           "language": language, "role_from_caption": role,
                           "caption": paragraph})
            number = end + 1
        elif re.match(r"^ {0,3}>", line):
            end = number + 1
            while end < len(lines):
                if re.match(r"^ {0,3}>", lines[end]):
                    end += 1
                elif (not lines[end].strip() and end + 1 < len(lines)
                      and re.match(r"^ {0,3}>", lines[end + 1])):
                    end += 1
                else:
                    break
            paragraph = preceding_paragraph(lines, number)
            quotes.append({"index": len(quotes), "line": number + 1,
                           "sha256": sha("".join(lines[number:end]).encode()),
                           "role_from_caption": caption_role(paragraph),
                           "caption": paragraph})
            number = end
        else:
            number += 1
    return fences, quotes


def inventory():
    records, skipped, errors = [], [], []
    for path in sorted((ROOT / "cases").rglob("*.md")):
        name = path.relative_to(ROOT).as_posix()
        text = path.read_text()
        generated_page = '<!-- Generated by python -m adfgvx.page_editions; edit data/source_editions.json. -->'
        if (path.name == "README.md" or text.startswith("# Reading location")
                or (path.parent == ROOT / 'cases/pages' and generated_page in text)):
            skipped.append(name)
            continue
        try:
            fences, quotes = displays(text)
        except ValueError as error:
            errors.append({"path": name, "error": str(error)})
            continue
        records.append({"path": name,
                        "convention_links": text.count(expected_legend(path)),
                        "obsolete_legends": text.count("**Reading layers:**"),
                        "titles": len(re.findall(r"^# ", text, re.M)),
                        "details_open": text.count("<details>"),
                        "details_close": text.count("</details>"),
                        "summaries": len(re.findall(r"<summary>[^<]+</summary>", text)),
                        "fences": fences, "quotes": quotes})
    return {"files": records, "skipped": skipped, "errors": errors}


def check(current, exceptions):
    failures = list(current["errors"])
    allowed = {(r["path"], r["kind"], r["sha256"]): r["role"]
               for r in exceptions["displays"]}
    used, roles = set(), Counter()
    for record in current["files"]:
        name = record["path"]
        def fail(message):
            failures.append({"path": name, "error": message})
        if record["convention_links"] != 1 or record["obsolete_legends"]:
            fail("Require one convention link and no repeated reading-layer legend")
        if record["titles"] != 1:
            fail("Require one page title")
        if not (record["details_open"] == record["details_close"] == record["summaries"]):
            fail("Evidence drawers need balanced details tags and one summary each")
        for kind in ("fences", "quotes"):
            for display in record[kind]:
                key = (name, kind, display["sha256"])
                role = display["role_from_caption"]
                if key in allowed:
                    used.add(key)
                    role = role or allowed[key]
                if not role:
                    fail("Unlabelled " + kind + " display at line " + str(display["line"]))
                roles[role or "unclassified"] += 1
    for key in sorted(set(allowed) - used):
        failures.append({"path": key[0], "error": "Stale or changed reviewed display exception"})
    return {"schema": "adfgvx-current-edition-structure-v2",
            "verified": not failures,
            "case_pages": len(current["files"]),
            "evidence_drawers": sum(r["details_open"] for r in current["files"]),
            "display_roles": dict(sorted(roles.items())),
            "failures": failures,
            "scope": "Current structure and visible labels. Source, cipher and readable-label checks run separately."}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--inventory-output", type=Path)
    args = parser.parse_args()
    current = inventory()
    if args.inventory_output:
        args.inventory_output.write_text(json.dumps(current, indent=2) + "\n")
    exceptions = json.loads((HERE / "display_exceptions.json").read_text())
    result = check(current, exceptions)
    if args.output:
        args.output.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result, indent=2))
    return 0 if result["verified"] else 1


if __name__ == "__main__":
    sys.exit(main())
